// Run with Vite: ego-browser nodejs < tests/ui/design-acceptance.mjs
// Isolated native transport and model replies. No real account, photo upload or model usage.
import assert from 'node:assert/strict';
const task=await taskSpace('Liubai simpler framing 0.9');
console.log({spaceId:task.spaceId});
const page=task.page('p1');
const modelCalls=()=>page.evaluate(()=>window.__qa.requests.filter(r=>/^generate_/.test(r.cmd)));
async function openAI(query=''){
 await page.goto('http://127.0.0.1:1420/tests/ui/app.html'+query);
 await page.waitForSelector('.frame-entry-row button:not([disabled])');
 await page.selectOption('select.language-select','en');
 await page.click("loc=role:button[name='AI design']");
 await page.waitForSelector('#style-direction',{state:'visible'});
}
await openAI('?legacy-style');
assert.deepEqual(await page.evaluate(()=>({cards:document.querySelectorAll('[name="art-look"]').length,tabs:document.querySelectorAll('.creative-tabs,.image-target').length,advanced:document.querySelector('.generation-options').open,brief:document.querySelector('#style-direction').value})),{cards:0,tabs:0,advanced:false,brief:''});
assert.equal((await modelCalls()).length,0,'Opening the AI dialog must not consume model usage');
assert.equal(await page.evaluate(()=>document.querySelector('.model-dialog [type=submit]').disabled),true);
await page.click('.model-dialog form > fieldset > .model-consent input');
await page.click('.model-dialog [type=submit]');
await page.waitForSelector('.art-suggestions img');
let calls=await modelCalls();
assert.equal(calls.length,1);
assert.equal(calls[0].cmd,'generate_complete_frame');
assert.equal(calls[0].args.config.frameDesign.style,'auto','A legacy film choice must not constrain the new request');
assert.equal(calls[0].args.config.frameDesign.placement,'auto');
assert.equal(calls[0].args.config.designDensity,'auto');
assert.equal(calls[0].args.config.frameDesign.notes,'','An empty brief must remain valid');
await page.fill('#style-direction','A quiet botanical border, no film marks');
assert.equal(await page.evaluate(()=>document.querySelector('.model-dialog form > fieldset > .model-consent input').checked),false,'Editing a brief must invalidate the previous consent');
await page.focus('.generation-options > summary');
await page.press('.generation-options > summary','Enter');
await page.selectOption('#art-placement','bottom');
await page.selectOption('#art-palette','mono');
await page.selectOption('#design-density','rich');
await page.click('.generation-options > summary');
await page.click('.model-dialog form > fieldset > .model-consent input');
await page.click('.model-dialog [type=submit]');
await page.waitForFunction(()=>window.__qa.requests.filter(r=>r.cmd==='generate_complete_frame').length===2&&!document.querySelector('.model-dialog fieldset').disabled);
calls=await modelCalls();
assert.equal(calls[1].args.config.frameDesign.notes,'A quiet botanical border, no film marks');
assert.equal(calls[1].args.config.frameDesign.placement,'bottom');
assert.equal(calls[1].args.config.frameDesign.palette,'mono');
assert.equal(calls[1].args.config.designDensity,'rich');
console.log('PASS: photo-led defaults, empty brief, legacy migration, optional constraints and consent gating.');

await openAI();
await page.fill('#style-direction','Keep this idea while changing models');
await page.click('.generation-options > summary');
await page.selectOption('#generation-method','sticker');
await page.waitForFunction(()=>document.querySelector('#generation-method')?.value==='sticker'&&!document.querySelector('.model-loading'));
assert.equal(await page.evaluate(()=>document.querySelector('#style-direction').value),'Keep this idea while changing models');
await page.click("loc=role:button[name='Change model']");
await page.waitForSelector('.models-config[open]');
await page.click("loc=role:button[name='Close model configuration']");
await page.waitForSelector('#style-direction',{state:'visible'});
assert.equal(await page.evaluate(()=>document.querySelector('#style-direction').value),'Keep this idea while changing models');
assert.equal(await page.evaluate(()=>document.querySelector('#generation-method').value),'sticker');
assert.equal((await modelCalls()).length,0);
console.log('PASS: changing model configuration preserves the brief and generation method without generating.');

await openAI('?connected-chatgpt');
await page.click('.generation-options > summary');
await page.selectOption('#generation-method','design');
await page.waitForSelector('.model-dialog form > fieldset > .model-consent input');
await page.click('.model-dialog form > fieldset > .model-consent input');
await page.waitForFunction(()=>!document.querySelector('.model-dialog [type=submit]').disabled);
await page.click('.model-dialog [type=submit]');
await page.waitForFunction(()=>document.querySelectorAll('.art-suggestions article').length===3);
assert.equal((await modelCalls())[0].cmd,'generate_art_frames');
console.log('PASS: existing ChatGPT analysis connection is checked with no duplicate login editor.');

await page.goto('http://127.0.0.1:1420/tests/ui/app.html');
await page.waitForSelector('.frame-entry-row button:not([disabled])');
await page.click("loc=role:button[name='Frame templates']");
await page.waitForSelector('.style-card');
await page.click("loc=role:button[name='Film']");
await page.waitForFunction(()=>document.querySelectorAll('.style-card').length===12&&!document.querySelector('.style-preview [aria-busy=true]'));
assert.equal(await page.evaluate(()=>document.querySelector('.template-adjustments').open),false);
assert.deepEqual(await page.evaluate(()=>[...document.querySelectorAll('.style-card strong')].map(x=>x.textContent)),['Film Edge','Amber Negative','Warm Photo Paper','35mm Full Scan','Warm Color Negative','Silver Negative','120 Medium Format','16mm Cine Scan','Super 8 Scan','Darkroom Contact','Cardboard Slide','Instant Photo Paper']);
await page.click('input[value="film-negative"]');
await page.waitForFunction(()=>!document.querySelector('.preview-image').getAttribute('aria-busy')||document.querySelector('.preview-image').getAttribute('aria-busy')==='false');
await page.click("loc=role:button[name='Apply selected style']");
await page.waitForSelector('.templates-dialog',{state:'hidden'});
assert.equal((await modelCalls()).length,0,'Selecting and applying local film templates must not invoke AI');
assert.equal(await page.evaluate(()=>document.querySelector('#frame-hex').value),'#1C201F');
assert.equal(await page.evaluate(()=>[...document.querySelectorAll('.settings-panel button')].some(b=>b.textContent.trim()==='Refine once')),false,'Local templates must not suggest AI refinement');
console.log('PASS: twelve local film templates apply without a model call; details remain optional.');

await page.goto('http://127.0.0.1:1420/tests/ui/app.html?refine');
await page.waitForSelector('.frame-entry-row button:not([disabled])');
await page.click("loc=role:button[name='Refine once']");
await page.waitForSelector('#style-direction',{state:'visible'});
await page.click('.model-dialog form > fieldset > .model-consent input');
await page.click('.model-dialog [type=submit]');
await page.waitForSelector('.refine-comparison img');
assert.equal((await modelCalls())[0].args.token,'refine');
assert.equal(await page.evaluate(()=>document.querySelectorAll('.art-suggestions article').length),1);
console.log('PASS: existing generated artwork retains its contextual refinement flow.');
await page.click("loc=role:button[name='Close AI design']");
await page.selectOption('select.language-select','zh-CN');
await page.click("loc=role:button[name='AI 设计']");
await page.waitForSelector('#style-direction',{state:'visible'});
assert.equal(await page.evaluate(()=>document.querySelector('#art-title').textContent),'AI 设计');
assert.equal(await page.evaluate(()=>document.querySelector('label[for=style-direction]').textContent),'你的想法（可选）');
await page.evaluate(()=>window.__qa.dragEnter(['/synthetic/a.jpg','/synthetic/b.jpg']));
await page.waitForSelector('.drop-overlay');
await page.evaluate(()=>window.__qa.dragLeave());
console.log('PASS: Chinese localization and existing grouped-drop listener remain available.');
console.log('All simplified design acceptance checks passed. Model calls above used fixture replies only.');
