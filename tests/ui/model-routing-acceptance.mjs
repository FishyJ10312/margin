// Run against the isolated Vite fixture with ego-browser nodejs.
import assert from 'node:assert/strict';
const task = await taskSpace('Margin model routing');
console.log({spaceId:task.spaceId});
const page = task.page('p1');
await page.goto('http://127.0.0.1:1420/tests/ui/app.html?connected-chatgpt&image-api-configured');
await page.waitForSelector('.art-trigger:not([disabled])');
await page.selectOption('.language-select', 'en');
await page.click('.art-trigger');
await page.waitForSelector('#style-direction');
const method = () => page.evaluate(() => document.querySelector('#generation-method')?.value);
const calls = () => page.evaluate(() => window.__qa.requests.filter(r => /^generate_/.test(r.cmd)));
assert.equal(await method(), 'design', 'Entering AI design with ChatGPT connected should start with analysis, even when another image provider is saved');
assert.equal(await page.evaluate(() => document.querySelector('#generation-method').getBoundingClientRect().height > 0), true);
assert.equal((await calls()).length, 0);
await page.click('.model-dialog form > fieldset > .model-consent input');
await page.click('.model-dialog [type=submit]');
await page.waitForFunction(() => document.querySelectorAll('.art-suggestions img').length === 3);
let sent = await calls();
assert.equal(sent[0].cmd, 'generate_art_frames');
assert.equal(sent[0].args.config.provider, 'chatgpt');
assert.equal(sent[0].args.apiKey, '');
console.log('PASS: saved image API does not affect ChatGPT analysis or require a key');

await page.selectOption('#generation-method', 'image');
await page.waitForFunction(() => document.querySelector('#generation-method')?.value === 'image');
await page.waitForSelector('#generation-setup');
assert.match(await page.evaluate(() => document.querySelector('#generation-setup').textContent), /API Key/);
assert.equal(await page.evaluate(() => document.querySelector('.model-dialog [type=submit]').disabled), true);
assert.equal((await calls()).length, 1);
await page.click("loc=role:button[name='Change model']");
await page.waitForSelector('#image-provider');
assert.equal(await page.evaluate(() => document.querySelector('#image-provider').value), 'openai');
await page.selectOption('#image-provider','codex');
await page.click('.models-config footer button[type=submit]');
await page.waitForSelector('.settings-notice');
await page.click("loc=role:button[name='Close model configuration']");
await page.waitForFunction(() => document.querySelector('#generation-method')?.value === 'image' &&
  !document.querySelector('#generation-setup'));
await page.click('.model-dialog form > fieldset > .model-consent input');
await page.click('.model-dialog [type=submit]');
await page.waitForSelector('.art-suggestions img');
sent = await calls();
assert.equal(sent[1].cmd, 'generate_complete_frame');
assert.equal(sent[1].args.config.image.provider, 'codex');
assert.equal(sent[1].args.config.provider, 'chatgpt');
assert.equal(sent[1].args.apiKey, '');
console.log('PASS: the full-frame API key check opens image settings, and local Codex generates without a key');
await task.finish({keep:[]});
