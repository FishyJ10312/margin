import assert from 'node:assert/strict';
const task = await taskSpace('Margin darkroom polish acceptance');
console.log({ spaceId: task.spaceId });
const page = task.page('p1');
const base = 'http://127.0.0.1:1420/tests/ui/app.html';
await page.goto(base + '?darkroom-polish');
await page.waitForFunction(() => window.__qa?.dropReady && document.querySelector('.palette-swatch'));
await page.selectOption('.language-select', 'en');
await page.cdp('Emulation.setDeviceMetricsOverride', {width:900,height:650,deviceScaleFactor:1,mobile:false});
await page.waitForFunction(() => !document.querySelector('.quick-template-grid button')?.disabled);
assert.equal(await page.evaluate(() => document.querySelector('.quick-template-grid').getBoundingClientRect().bottom <
    document.querySelector('.inspector-bottom').getBoundingClientRect().top), true);
// Keep the pointer down until a new close-up result arrives. Updating
// that image must not add the same movement again to the drag handle.
await page.waitForSelector('.mark-handle');
const mark = await page.evaluate(() => {
  const rect = document.querySelector('.mark-handle').getBoundingClientRect();
  return { x: rect.left, y: rect.top, cx: rect.left + rect.width / 2, cy: rect.top + rect.height / 2 };
});
await page.mouse.move(mark.cx, mark.cy, {label:'Find the watermark handle'});
await page.mouse.down();
await page.mouse.move(mark.cx - 24, mark.cy - 10, {label:'Move the watermark left'});
await page.waitForFunction(() => window.__qa.detailControl.rendered.at(-1)?.settings.watermark.offsetX < 0);
const dragged = await page.evaluate(() => document.querySelector('.mark-handle').getBoundingClientRect().left);
assert.ok(Math.abs(mark.x - dragged - 24) < 2);
await page.mouse.up();
await page.waitForFunction(() => window.__qa.savedSettings.watermark.offsetX < 0);
console.log('PASS: watermark pointer tracking stays anchored while the close-up catches up');
await page.click('.quick-template-grid button >> nth=0');
await page.keyboard.press('ArrowRight');
await page.waitForFunction(() => window.__qa.requests.filter(r => r.cmd === 'get_preview').at(-1)?.args.settings.artwork?.design?.id === 'keyline' &&
    !document.querySelector('.apply-trial').disabled);
assert.equal(await page.evaluate(() => window.__qa.savedSettings.artwork), null);
await page.focus('.trial-actions button >> nth=0');
await page.keyboard.down('Space');
await page.waitForFunction(() => document.querySelector('.trial-actions button').getAttribute('aria-pressed') === 'true');
await page.keyboard.up('Space');
await page.waitForFunction(() => document.querySelector('.trial-actions button').getAttribute('aria-pressed') === 'false');
await page.click('.apply-trial');
await page.waitForFunction(() => window.__qa.savedSettings.artwork?.design?.id === 'keyline');
console.log('PASS: smallest-window visibility, arrow-key trial, held original, explicit apply');
await page.evaluate(() => window.__qa.drop(['/synthetic/B.jpg', '/synthetic/C.jpg']));
await page.waitForFunction(() => document.querySelectorAll('.thumbnail').length === 3);
const thumb = index => '.thumbnail >> nth=' + index;
const color = hex => '.palette-swatch[aria-label*="' + hex + '"]';
await page.click(thumb(1));
await page.click('.settings-scope button >> nth=1');
await page.click('.ratio-grid button >> nth=1');
await page.click(color('#171A17'));
await page.waitForFunction(() => window.__qa.catalog.photos[1].settings?.frameColor === '#171A17');
await page.click(thumb(0));
await page.keyboard.down('Shift');
await page.click(thumb(1));
await page.keyboard.up('Shift');
await page.click(color('#F3ECDD'));
await page.waitForFunction(() => window.__qa.catalog.photos.slice(0, 2).every(p => p.settings?.frameColor === '#F3ECDD'));
const photos = await page.evaluate(() => window.__qa.catalog.photos);
assert.equal(photos[0].settings.ratio, null);
assert.deepEqual(photos[1].settings.ratio, {width:1,height:1});
assert.equal(photos[2].settings, undefined);
assert.notEqual(...await page.evaluate(() => [...document.querySelectorAll('.thumbnail.selected')].map(e => getComputedStyle(e).boxShadow)));
await page.keyboard.press('Meta+z');
await page.waitForFunction(() => !window.__qa.catalog.photos[0].settings && window.__qa.catalog.photos[1].settings.frameColor === '#171A17');
await page.keyboard.press('Meta+Shift+z');
await page.waitForFunction(() => window.__qa.catalog.photos[0].settings?.frameColor === '#F3ECDD');
console.log('PASS: mixed selection preserves unrelated fields and undo/redo restores individual values');
await page.click(thumb(1));
await page.click('.export-primary');
await page.click('.export-targets button >> nth=2');
await page.click('input[name=export-scope][value=all]');
await page.click('.start-export');
await page.waitForFunction(() => !document.querySelector('.export-review').open);
const attempt = await page.evaluate(() => window.__qa.requests.filter(r => r.cmd === 'start_batch').at(-1).args);
assert.deepEqual(attempt.uniformRatio, {width:4,height:5});
assert.notEqual(attempt.settings.frameColor, '#F3ECDD');
assert.equal(attempt.settings.ratio, null);
assert.equal(attempt.photoIds.length, 3);
assert.equal(await page.evaluate(() => window.__qa.catalog.photos[1].settings.ratio.width), 1);
await page.evaluate(() => {
  const args = window.__qa.requests.filter(r => r.cmd === 'start_batch').at(-1).args;
  window.__qa.emitBatch({id:'test-finished',revision:2,status:'completed',outputDirectory:args.outputDirectory,items:[]});
});
await page.click('.agent-connect-trigger');
await page.waitForSelector('#agent-enabled');
await page.click('#agent-enabled');
await page.waitForFunction(() => window.__qa.agentState.enabled);
await page.keyboard.press('Escape');
await page.waitForSelector('.agent-connection[open]', {state:'hidden'});
await page.evaluate(() => window.__qa.agent('margin_export_photos', {outputDirectory:'/synthetic/mcp',scope:'all',uniformRatio:{width:4,height:5}}).then(result => result.photoCount));
const agent = await page.evaluate(() => window.__qa.requests.filter(r => r.cmd === 'start_batch').at(-1).args);
assert.deepEqual(agent.settings, attempt.settings);
assert.deepEqual(agent.photoIds, attempt.photoIds);
assert.deepEqual(agent.uniformRatio, attempt.uniformRatio);
console.log('PASS: native dispatch contracts match between the export dialog and MCP');
await task.finish({keep:[]});
